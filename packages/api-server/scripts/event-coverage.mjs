#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const PKG_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const REPO_ROOT = resolve(PKG_ROOT, "..", "..");
const TSCONFIG = join(PKG_ROOT, "tsconfig.json");
const EVENTS_FILE = join(PKG_ROOT, "src", "events.ts");
const PERSIST_SAGA = join(
  PKG_ROOT,
  "src",
  "modules",
  "usage",
  "sagas",
  "persist-activity.ts",
);
const DOC_PATH = join(REPO_ROOT, "docs", "activity-events.md");
const DOC_MARKER =
  "<!-- generated by packages/api-server/scripts/event-coverage.mjs, do not edit — run `mise run docs:generate:activity-events` -->";

const ENUM_NAME = "EventType";
const EMIT_FN = "emit";
const SUBSCRIBE_FN = "ofType";

const NOT_TRACKED = [
  ["e2e", "Test-only surface, never reachable by a user."],
  [
    "approvals",
    "Emits events for live UI updates, but nothing to the activity log: every decision is already a durable, timestamped row in `pending_approvals`, which the report reads directly.",
  ],
  [
    "terms",
    "Acceptance is a one-time legal fact held in `terms_acceptances`; it belongs to consent tracking rather than usage.",
  ],
  [
    "egress-rules",
    "Rule edits are an administrative action, not product usage. Observed egress traffic is covered separately.",
  ],
];

function die(message) {
  console.error(`event-coverage: ${message}`);
  process.exit(1);
}

function sourceFileNames() {
  const host = {
    ...ts.sys,
    onUnRecoverableConfigFileDiagnostic: (d) =>
      die(ts.flattenDiagnosticMessageText(d.messageText, "\n")),
  };
  const parsed = ts.getParsedCommandLineOfConfigFile(TSCONFIG, {}, host);
  if (!parsed) die(`could not read ${relative(REPO_ROOT, TSCONFIG)}`);
  return parsed.fileNames;
}

function parse(file) {
  return ts.createSourceFile(
    file,
    readFileSync(file, "utf8"),
    ts.ScriptTarget.Latest,
    false,
  );
}

function registryMembers() {
  const source = parse(EVENTS_FILE);
  let members = null;
  ts.forEachChild(source, (node) => {
    if (ts.isEnumDeclaration(node) && node.name.text === ENUM_NAME) {
      members = node.members.map((m) => m.name.getText(source));
    }
  });
  return members;
}

function calleeName(call) {
  const target = call.expression;
  if (ts.isIdentifier(target)) return target.text;
  if (ts.isPropertyAccessExpression(target)) return target.name.text;
  return null;
}

function eachReference(source, onReference) {
  const visit = (node, enclosingCall) => {
    const inside = ts.isCallExpression(node) ? calleeName(node) : enclosingCall;
    if (
      ts.isPropertyAccessExpression(node) &&
      ts.isIdentifier(node.expression) &&
      node.expression.text === ENUM_NAME
    ) {
      const { line } = source.getLineAndCharacterOfPosition(
        node.getStart(source),
      );
      onReference(node.name.text, inside, line + 1);
    }
    ts.forEachChild(node, (child) => visit(child, inside));
  };
  visit(source, null);
}

function record(index, member, site) {
  const sites = index.get(member);
  if (sites) sites.push(site);
  else index.set(member, [site]);
}

function templateLabel(node) {
  let out = node.head.text;
  for (const span of node.templateSpans) {
    const expr = span.expression;
    const name = ts.isPropertyAccessExpression(expr) ? expr.name.text : "value";
    out += `<${name}>${span.literal.text}`;
  }
  return out;
}

function typeLabelsIn(node) {
  const labels = [];
  const visit = (n) => {
    if (ts.isStringLiteral(n)) {
      labels.push(n.text);
      return;
    }
    if (ts.isTemplateExpression(n)) {
      labels.push(templateLabel(n));
      return;
    }
    if (ts.isConditionalExpression(n)) {
      visit(n.whenTrue);
      visit(n.whenFalse);
      return;
    }
    ts.forEachChild(n, visit);
  };
  visit(node);
  return labels;
}

function rowTypesByEvent() {
  const source = parse(PERSIST_SAGA);
  const byEvent = new Map();

  const collect = (statement) => {
    const events = [];
    const rowTypes = [];
    const visit = (node, enclosingCall) => {
      const inside = ts.isCallExpression(node)
        ? calleeName(node)
        : enclosingCall;
      if (
        ts.isPropertyAccessExpression(node) &&
        ts.isIdentifier(node.expression) &&
        node.expression.text === ENUM_NAME &&
        inside === SUBSCRIBE_FN
      ) {
        events.push(node.name.text);
      }
      const named =
        (ts.isPropertyAssignment(node) || ts.isVariableDeclaration(node)) &&
        ts.isIdentifier(node.name) &&
        node.name.text === "type";
      if (named && node.initializer) {
        rowTypes.push(...typeLabelsIn(node.initializer));
      }
      ts.forEachChild(node, (child) => visit(child, inside));
    };
    visit(statement, null);
    for (const event of events) {
      const merged = new Set([...(byEvent.get(event) ?? []), ...rowTypes]);
      byEvent.set(event, [...merged]);
    }
  };

  const walk = (node) => {
    if (ts.isExpressionStatement(node)) {
      collect(node);
      return;
    }
    ts.forEachChild(node, walk);
  };
  walk(source);
  return byEvent;
}

function sourceLabel(site) {
  const file = site.split(":")[0];
  const inModule = file.match(/\/modules\/([^/]+)\//);
  if (inModule) return inModule[1];
  const inApp = file.match(/\/apps\/[^/]+\/(.+)\.ts$/);
  if (inApp) return inApp[1];
  return (file.split("/").pop() ?? file).replace(/\.ts$/, "");
}

function renderDoc(members, emitted, rowTypes) {
  const out = [
    DOC_MARKER,
    "",
    "# Activity events",
    "",
    "What the platform records when someone uses it. Each row is one domain event: the name it is emitted under, the `activity_events.type` it is stored as, and the part of the system it fires from.",
    "",
    "This table is generated from the source, so it cannot drift from what the code actually emits. Conceptual background — why these are collected, how actors are pseudonymized, what the numbers do and do not mean — is in [usage tracking](architecture/usage-tracking.md).",
    "",
    "A row type shown as `prefix_<action>` is stored with the action substituted, so `experiment_<action>` is written as `experiment_started`, `experiment_stopped` or `experiment_deleted`.",
    "",
    "Events marked *elsewhere* are consumed, but not by the activity log: they drive live UI updates, the `agents` mirror, or channel management. They will not appear in `activity_events`, so they answer nothing about usage.",
    "",
    `| Event | Stored as | Fired from |`,
    `| --- | --- | --- |`,
  ];

  for (const member of members) {
    const stored = rowTypes.get(member) ?? [];
    const from = [...new Set((emitted.get(member) ?? []).map(sourceLabel))];
    out.push(
      `| \`${member}\` | ${
        stored.length > 0
          ? stored.map((s) => `\`${s}\``).join(", ")
          : "_elsewhere_"
      } | ${from.length > 0 ? from.join(", ") : "—"} |`,
    );
  }

  out.push(
    "",
    "## Deliberately not recorded",
    "",
    "User-facing components that emit no event, and why.",
    "",
    "| Component | Reason |",
    "| --- | --- |",
  );
  for (const [name, reason] of NOT_TRACKED) {
    out.push(`| \`${name}\` | ${reason} |`);
  }
  out.push("");
  return out.join("\n");
}

const members = registryMembers();
if (!members)
  die(`no \`${ENUM_NAME}\` enum in ${relative(REPO_ROOT, EVENTS_FILE)}`);

const emitted = new Map();
const consumed = new Map();
const unknown = new Map();

for (const file of sourceFileNames()) {
  if (file.endsWith(".d.ts") || file.endsWith(".test.ts")) continue;
  if (file.split(sep).includes("__tests__")) continue;
  if (resolve(file) === resolve(EVENTS_FILE)) continue;

  const source = parse(file);
  const where = relative(REPO_ROOT, file);
  eachReference(source, (member, insideCall, line) => {
    const site = `${where}:${line}`;
    if (!members.includes(member)) record(unknown, member, site);
    else if (insideCall === EMIT_FN) record(emitted, member, site);
    else record(consumed, member, site);
  });
}

if (process.argv.includes("--doc") || process.argv.includes("--check-doc")) {
  const rendered = renderDoc(members, emitted, rowTypesByEvent());
  const target = relative(REPO_ROOT, DOC_PATH);
  if (process.argv.includes("--check-doc")) {
    let current = null;
    try {
      current = readFileSync(DOC_PATH, "utf8");
    } catch {}
    if (current !== rendered) {
      console.error(
        `\n${target} is stale. Run \`mise run docs:generate:activity-events\`.\n`,
      );
      process.exit(1);
    }
    console.log(`${target} matches the generated projection.`);
    process.exit(0);
  }
  writeFileSync(DOC_PATH, rendered);
  console.log(`wrote ${target} (${members.length} events)`);
  process.exit(0);
}

if (process.argv.includes("--list")) {
  const width = Math.max(...members.map((m) => m.length));
  for (const member of members) {
    const emits = emitted.get(member)?.length ?? 0;
    const uses = consumed.get(member)?.length ?? 0;
    console.log(`${member.padEnd(width)}  emitted=${emits}  consumed=${uses}`);
  }
  console.log(`\n${members.length} events`);
}

const problems = [];
for (const member of members) {
  const emits = emitted.get(member) ?? [];
  const uses = consumed.get(member) ?? [];
  if (emits.length === 0 && uses.length === 0) {
    problems.push(
      `${member}: declared but never emitted and never consumed — delete it`,
    );
  } else if (emits.length === 0) {
    problems.push(
      `${member}: consumed at ${uses[0]} but never emitted — the subscriber can never run`,
    );
  } else if (uses.length === 0) {
    problems.push(
      `${member}: emitted at ${emits[0]} but nothing consumes it — the interaction is dropped`,
    );
  }
}
for (const [member, sites] of unknown) {
  problems.push(
    `${ENUM_NAME}.${member} at ${sites[0]} is not a member of the registry`,
  );
}

if (problems.length > 0) {
  console.error(
    `\nevent-coverage: ${problems.length} uncovered event${problems.length === 1 ? "" : "s"}\n`,
  );
  for (const problem of problems) console.error(`  ${problem}`);
  console.error(
    `\nEvery event in src/events.ts must have an emit site and a subscriber.\n` +
      `Add the missing half, or remove the event.\n`,
  );
  process.exit(1);
}

console.log(
  `event-coverage: ${members.length} events, all emitted and consumed`,
);
